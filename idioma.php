        $codigo = strtolower(trim($partes[0]));

        $calidad = isset($partes[1])
            ? (float) $partes[1]
            : 1.0;

        $codigo = str_replace('_', '-', $codigo);

        $preferencias[] = [
            'codigo' => $codigo,
            'calidad' => $calidad,
            'posicion' => $posicion
        ];
